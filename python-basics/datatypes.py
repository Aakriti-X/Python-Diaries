# datatypes specifies the type of values a variable holds

# Python Datatypes

# 1. Integer
age = 20
print("Integer:", age)
print(type(age))


# 2. Float
height = 5.6
print("\nFloat:", height)
print(type(height))


# 3. String
name = "XYZ"
print("\nString:", name)
print(type(name))


# 4. Boolean
is_student = True
print("\nBoolean:", is_student)
print(type(is_student))


# 5. List
fruits = ["Apple", "Banana", "Mango"]
print("\nList:", fruits)
print(type(fruits))


# 6. Tuple
student = ("xyz",19,"Computer Engineering")
print("\nTuple:", student)
print(type(student))


# 7. Set
numbers = {1, 2, 3, 4}
print("\nSet:", numbers)
print(type(numbers))


# 8. Dictionary
student = {
    "name": "XYZ",
    "age": 19,
    "course": "Computer Engineering"
}
print("\nDictionary:", student)
print(type(student))